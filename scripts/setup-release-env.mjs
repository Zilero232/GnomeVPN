import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { $, findGh, isWindows, reporter, workspace } from './lib/shell.mjs';

const log = reporter('setup:release');

const releaseEnv = join(workspace, '.env.release');
const keystore = join(workspace, 'apps', 'tauri', 'gnomevpn.keystore');
const keytool = join(process.env.JAVA_HOME ?? '', 'bin', isWindows ? 'keytool.exe' : 'keytool');

const installGhViaWinget = async () => {
  const args =
    'install --id GitHub.cli -e --source winget --accept-package-agreements --accept-source-agreements';

  if (isWindows) {
    await $`cmd /c winget ${args.split(' ')}`.nothrow();
  } else {
    await $`winget ${args.split(' ')}`.nothrow();
  }
};

const ensureGh = async () => {
  if (await findGh()) {
    log.info('gh: present');

    return;
  }

  log.step('installing GitHub CLI via winget');
  await installGhViaWinget();

  if (!(await findGh())) {
    log.fail(
      [
        'could not install gh automatically — install it by hand:',
        '  winget install --id GitHub.cli   (or https://cli.github.com)',
        'then run `gh auth login` and re-run `bun run setup:release`'
      ].join('\n')
    );
  }

  log.info('gh ready — open a new shell so it lands on PATH, then run `gh auth login`');
};

const appendReleaseEnv = (lines) => {
  const existing = existsSync(releaseEnv) ? readFileSync(releaseEnv, 'utf8') : '';
  const fresh = lines.filter(({ key }) => !existing.includes(`${key}=`));

  if (!fresh.length) {
    return;
  }

  const block = fresh.map(({ key, value }) => `${key}=${value}`).join('\n');

  if (existing) {
    appendFileSync(releaseEnv, `\n${block}\n`);
  } else {
    writeFileSync(
      releaseEnv,
      `# Generated by setup:release — gitignored, never commit.\n${block}\n`
    );
  }

  log.info(`wrote ${fresh.map((line) => line.key).join(', ')} to .env.release`);
};

const ensureKeystore = async () => {
  if (process.env.ANDROID_KEY_BASE64) {
    log.info('android keystore: already configured');

    return;
  }

  if (!existsSync(keytool)) {
    log.fail(`keytool not found at ${keytool} — set JAVA_HOME to the Android Studio JBR`);
  }

  const alias = 'gnomevpn';
  const password = randomBytes(24).toString('base64url');

  log.step('generating Android release keystore');
  await $`${keytool} -genkeypair -v -keystore ${keystore} -alias ${alias} -keyalg RSA -keysize 2048 -validity 10000 -storepass ${password} -keypass ${password} -dname ${'CN=GnomeVPN, O=GnomeVPN, C=RU'}`;

  appendReleaseEnv([
    { key: 'ANDROID_KEY_ALIAS', value: alias },
    { key: 'ANDROID_KEY_PASSWORD', value: password },
    { key: 'ANDROID_KEY_BASE64', value: readFileSync(keystore).toString('base64') }
  ]);

  log.info('keystore created — back up apps/tauri/gnomevpn.keystore off the repo');
};

await ensureGh();
await ensureKeystore();

log.info('release environment ready');
