import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const overlay = join(here, '..', 'android');
const libs = join(overlay, 'libs');
const generated = join(here, '..', 'gen', 'android');
const appMain = join(generated, 'app', 'src', 'main');

const GENERATED = ['MainActivity.kt'];

if (!existsSync(generated)) {
  console.error('[android] gen/android is missing — run `tauri android init` first');
  process.exit(1);
}

const copyLibs = () => {
  const abis = readdirSync(libs, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);

  for (const abi of abis) {
    const to = join(appMain, 'jniLibs', abi);
    mkdirSync(to, { recursive: true });
    cpSync(join(libs, abi), to, { recursive: true });
  }

  return abis;
};

// Kotlin sources removed from the overlay have to disappear from the generated
// project too — a leftover file still compiles and can reference code that is
// no longer there.
const copySources = () => {
  const from = join(overlay, 'java');
  const to = join(appMain, 'java', 'app', 'gnomevpn', 'mobile');
  const ours = readdirSync(from);

  mkdirSync(to, { recursive: true });

  for (const entry of readdirSync(to)) {
    if (entry.endsWith('.kt') && !ours.includes(entry) && !GENERATED.includes(entry)) {
      rmSync(join(to, entry));
    }
  }

  cpSync(from, to, { recursive: true });

  return ours;
};

// The manifest is regenerated by `tauri android init`, so the VpnService entry
// has to be re-applied on every run rather than committed once.
const patchManifest = () => {
  const path = join(appMain, 'AndroidManifest.xml');
  const source = readFileSync(path, 'utf8');

  if (source.includes('GnomeVpnService')) {
    return false;
  }

  const permissions = [
    '<uses-permission android:name="android.permission.FOREGROUND_SERVICE" />',
    '<uses-permission android:name="android.permission.FOREGROUND_SERVICE_SPECIAL_USE" />',
    '<uses-permission android:name="android.permission.POST_NOTIFICATIONS" />',
  ].join('\n    ');

  const service = [
    '<service',
    '            android:name=".GnomeVpnService"',
    '            android:exported="false"',
    '            android:permission="android.permission.BIND_VPN_SERVICE"',
    '            android:foregroundServiceType="specialUse">',
    '            <property',
    '                android:name="android.app.PROPERTY_SPECIAL_USE_FGS_SUBTYPE"',
    '                android:value="vpn" />',
    '            <intent-filter>',
    '                <action android:name="android.net.VpnService" />',
    '            </intent-filter>',
    '        </service>',
  ].join('\n');

  // xray is an executable, not a library: Android only runs it from disk, and
  // with extractNativeLibs=false it stays compressed inside the APK.
  const patched = source
    .replace(
      '<uses-permission android:name="android.permission.INTERNET" />',
      `<uses-permission android:name="android.permission.INTERNET" />\n    ${permissions}`,
    )
    .replace('    <application', '    <application\n        android:extractNativeLibs="true"')
    .replace('    </application>', `        ${service}\n    </application>`);

  writeFileSync(path, patched, 'utf8');

  return true;
};

const abis = copyLibs();
const sources = copySources();
const patched = patchManifest();

// biome-ignore lint/suspicious/noConsole: standalone CLI script, console is the output channel
console.log(
  `[android] libs: ${abis.join(', ')} | sources: ${sources.join(', ')} | manifest: ${patched ? 'patched' : 'already patched'}`,
);
