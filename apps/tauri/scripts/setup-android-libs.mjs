import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const overlay = join(here, '..', 'android');
const libs = join(overlay, 'libs');
const generated = join(here, '..', 'gen', 'android');
const appMain = join(generated, 'app', 'src', 'main');

const GENERATED = ['MainActivity.kt'];

// Built by cargo into jniLibs rather than copied from the overlay, so the
// cleanup below must leave it alone.
const CARGO_LIB = 'libgnomevpn_lib.so';

if (!existsSync(generated)) {
  console.error('[android] gen/android is missing — run `tauri android init` first');
  process.exit(1);
}

// A binary renamed in the overlay leaves its predecessor behind in jniLibs,
// where it still ships inside the APK — libxray.so outlived the move to
// hysteria that way, and the tunnel failed at runtime looking for a name the
// APK no longer carried.
const copyLibs = () => {
  const abis = readdirSync(libs, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);

  const removed = [];

  for (const abi of abis) {
    const to = join(appMain, 'jniLibs', abi);
    const ours = readdirSync(join(libs, abi));

    mkdirSync(to, { recursive: true });

    for (const entry of readdirSync(to)) {
      if (entry !== CARGO_LIB && !ours.includes(entry)) {
        rmSync(join(to, entry), { recursive: true });
        removed.push(`${abi}/${entry}`);
      }
    }

    cpSync(join(libs, abi), to, { recursive: true });
  }

  return { abis, removed };
};

// Kotlin sources removed from the overlay have to disappear from the generated
// project too — a leftover file still compiles and can reference code that is
// no longer there.
const copySources = () => {
  const from = join(overlay, 'java');
  const to = join(appMain, 'java', 'app', 'gnomevpn', 'mobile');
  const ours = readdirSync(from);

  mkdirSync(to, { recursive: true });

  for (const entry of readdirSync(to)) {
    if (entry.endsWith('.kt') && !ours.includes(entry) && !GENERATED.includes(entry)) {
      rmSync(join(to, entry));
    }
  }

  cpSync(from, to, { recursive: true });

  return ours;
};

// `tauri icon` writes its own mipmaps into gen/android, so our drawables are
// merged in rather than replacing the directory.
const copyResources = () => {
  const from = join(overlay, 'res');

  if (!existsSync(from)) {
    return [];
  }

  cpSync(from, join(appMain, 'res'), { recursive: true });

  return readdirSync(from);
};

// The manifest is regenerated by `tauri android init`, so the VpnService entry
// has to be re-applied on every run rather than committed once.
const patchManifest = () => {
  const path = join(appMain, 'AndroidManifest.xml');
  const source = readFileSync(path, 'utf8');

  const permissions = [
    '<uses-permission android:name="android.permission.FOREGROUND_SERVICE" />',
    '<uses-permission android:name="android.permission.FOREGROUND_SERVICE_SPECIAL_USE" />',
    '<uses-permission android:name="android.permission.POST_NOTIFICATIONS" />',
    '<uses-permission android:name="android.permission.ACCESS_NETWORK_STATE" />',
  ].join('\n    ');

  const vpnService = [
    '<service',
    '            android:name=".GnomeVpnService"',
    '            android:exported="false"',
    '            android:permission="android.permission.BIND_VPN_SERVICE"',
    '            android:foregroundServiceType="specialUse">',
    '            <property',
    '                android:name="android.app.PROPERTY_SPECIAL_USE_FGS_SUBTYPE"',
    '                android:value="vpn" />',
    '            <intent-filter>',
    '                <action android:name="android.net.VpnService" />',
    '            </intent-filter>',
    '        </service>',
  ].join('\n');

  const tileService = [
    '<service',
    '            android:name=".VpnTileService"',
    '            android:exported="true"',
    '            android:icon="@drawable/ic_tile_vpn"',
    '            android:label="@string/app_name"',
    '            android:permission="android.permission.BIND_QUICK_SETTINGS_TILE">',
    '            <intent-filter>',
    '                <action android:name="android.service.quicksettings.action.QS_TILE" />',
    '            </intent-filter>',
    '        </service>',
  ].join('\n');

  // hysteria is an executable, not a library: Android only runs it from disk,
  // and with extractNativeLibs=false it stays compressed inside the APK.
  const steps = [
    {
      has: 'FOREGROUND_SERVICE_SPECIAL_USE',
      find: '<uses-permission android:name="android.permission.INTERNET" />',
      put: `<uses-permission android:name="android.permission.INTERNET" />\n    ${permissions}`,
    },
    {
      has: 'ACCESS_NETWORK_STATE',
      find: '<uses-permission android:name="android.permission.INTERNET" />',
      put: `<uses-permission android:name="android.permission.INTERNET" />\n    <uses-permission android:name="android.permission.ACCESS_NETWORK_STATE" />`,
    },
    {
      has: 'extractNativeLibs',
      find: '    <application',
      put: '    <application\n        android:extractNativeLibs="true"',
    },
    {
      has: 'GnomeVpnService',
      find: '    </application>',
      put: `        ${vpnService}\n    </application>`,
    },
    {
      has: 'VpnTileService',
      find: '    </application>',
      put: `        ${tileService}\n    </application>`,
    },
  ];

  const applied = [];

  const inserted = steps.reduce((xml, step) => {
    if (xml.includes(step.has)) {
      return xml;
    }

    applied.push(step.has);

    return xml.replace(step.find, step.put);
  }, source);

  // A tile is drawn as a tinted silhouette, so a manifest left over from an
  // earlier run still points the tile at the launcher icon and renders it as a
  // white blob. The insert above is skipped once the service is present, which
  // is why this rewrite is unconditional.
  const patched = inserted.replace(
    /(android:name="\.VpnTileService"\s*\n\s*android:exported="true"\s*\n\s*android:icon=")[^"]*(")/,
    '$1@drawable/ic_tile_vpn$2',
  );

  if (applied.length === 0 && patched === source) {
    return false;
  }

  writeFileSync(path, patched, 'utf8');

  return true;
};

const { abis, removed } = copyLibs();
const sources = copySources();
const resources = copyResources();
const patched = patchManifest();

// biome-ignore lint/suspicious/noConsole: standalone CLI script, console is the output channel
console.log(
  `[android] libs: ${abis.join(', ')}${removed.length ? ` | removed: ${removed.join(', ')}` : ''} | sources: ${sources.join(', ')} | res: ${resources.join(', ') || 'none'} | manifest: ${patched ? 'patched' : 'already patched'}`,
);
