import { readFileSync, writeFileSync } from 'node:fs';

// Add a permission by putting its name here — each entry becomes its own
// idempotent step below.
const PERMISSIONS = [
  'FOREGROUND_SERVICE',
  'FOREGROUND_SERVICE_SPECIAL_USE',
  'POST_NOTIFICATIONS',
  'WAKE_LOCK',
  'REQUEST_IGNORE_BATTERY_OPTIMIZATIONS',
];

const PERMISSION_ANCHOR = '<uses-permission android:name="android.permission.INTERNET" />';
const APPLICATION_END = '    </application>';

const VPN_SERVICE = `<service
            android:name=".GnomeVpnService"
            android:stopWithTask="false"
            android:exported="false"
            android:permission="android.permission.BIND_VPN_SERVICE"
            android:foregroundServiceType="specialUse">
            <property
                android:name="android.app.PROPERTY_SPECIAL_USE_FGS_SUBTYPE"
                android:value="vpn" />
            <intent-filter>
                <action android:name="android.net.VpnService" />
            </intent-filter>
        </service>`;

const TILE_SERVICE = `<service
            android:name=".VpnTileService"
            android:exported="true"
            android:icon="@drawable/ic_tile_vpn"
            android:label="@string/app_name"
            android:permission="android.permission.BIND_QUICK_SETTINGS_TILE">
            <intent-filter>
                <action android:name="android.service.quicksettings.action.QS_TILE" />
            </intent-filter>
        </service>`;

const permissionStep = (permission) => ({
  has: permission,
  find: PERMISSION_ANCHOR,
  put: `${PERMISSION_ANCHOR}\n    <uses-permission android:name="android.permission.${permission}" />`,
});

// hysteria is an executable, not a library: Android only runs it from disk, and
// with extractNativeLibs=false it stays compressed inside the APK.
const STEPS = [
  ...PERMISSIONS.map(permissionStep),
  {
    has: 'extractNativeLibs',
    find: '    <application',
    put: '    <application\n        android:extractNativeLibs="true"',
  },
  {
    has: 'GnomeVpnService',
    find: APPLICATION_END,
    put: `        ${VPN_SERVICE}\n${APPLICATION_END}`,
  },
  {
    has: 'stopWithTask',
    find: '            android:name=".GnomeVpnService"',
    put: '            android:name=".GnomeVpnService"\n            android:stopWithTask="false"',
  },
  {
    has: 'VpnTileService',
    find: APPLICATION_END,
    put: `        ${TILE_SERVICE}\n${APPLICATION_END}`,
  },
];

// A tile is drawn as a tinted silhouette, so a manifest left over from an
// earlier run still points the tile at the launcher icon and renders it as a
// white blob. The inserts above are skipped once the service is present, which
// is why this rewrite is unconditional.
const retargetTileIcon = (xml) =>
  xml.replace(
    /(android:name="\.VpnTileService"\s*\n\s*android:exported="true"\s*\n\s*android:icon=")[^"]*(")/,
    '$1@drawable/ic_tile_vpn$2',
  );

// android:foregroundServiceType="vpn" is a runtime constant, not a manifest flag
// value — AAPT rejects it. The manifest declares specialUse plus the vpn subtype
// property; the VpnService supplies FOREGROUND_SERVICE_TYPE_SPECIAL_USE at runtime.
// tauri android init preserves an existing manifest, so a run that already has the
// old "vpn" value would never be re-inserted — hence this unconditional heal.
const SUBTYPE_PROPERTY =
  '<property\n                android:name="android.app.PROPERTY_SPECIAL_USE_FGS_SUBTYPE"\n                android:value="vpn" />';

const normalizeVpnService = (xml) => {
  const withType = xml.replace(
    /(\.GnomeVpnService"[\s\S]*?android:foregroundServiceType=")vpn(")/,
    '$1specialUse$2',
  );

  if (withType.includes('PROPERTY_SPECIAL_USE_FGS_SUBTYPE')) {
    return withType;
  }

  return withType.replace(
    /(android:foregroundServiceType="specialUse">\n)(\s*)(<intent-filter>)/,
    `$1$2${SUBTYPE_PROPERTY}\n$2$3`,
  );
};

const dropStalePermissions = (xml) =>
  xml
    .replace(
      /\s*<uses-permission android:name="android\.permission\.FOREGROUND_SERVICE_VPN" \/>/,
      '',
    )
    .replace(
      /\s*<uses-permission android:name="android\.permission\.ACCESS_NETWORK_STATE" \/>/,
      '',
    );

// The manifest is regenerated by `tauri android init`, so every entry has to be
// re-applied on each run rather than committed once.
export const patchManifest = (path) => {
  const source = readFileSync(path, 'utf8');

  const inserted = STEPS.reduce(
    (xml, step) => (xml.includes(step.has) ? xml : xml.replace(step.find, step.put)),
    source,
  );

  const patched = dropStalePermissions(normalizeVpnService(retargetTileIcon(inserted)));

  if (patched === source) {
    return false;
  }

  writeFileSync(path, patched, 'utf8');

  return true;
};
